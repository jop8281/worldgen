/** A documented shell command: the line's executable part, comments stripped, `\` continuations joined. */
function shCommands(markdown: string): string[] {
  const out: string[] = [];
  for (const block of markdown.matchAll(/```sh\n([\s\S]*?)```/g)) {
    const joined = block[1]!.replace(/\\\n\s*/g, ' ');
    for (const raw of joined.split('\n')) {
      const line = raw.replace(/\s+#.*$/, '').trim();
      if (line !== '' && !line.startsWith('#')) out.push(line);
    }
  }
  return out;
}

