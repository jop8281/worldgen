interface DocLine { readonly file: string; readonly line: number; readonly text: string }

/** Every command line in a file's sh blocks with its 1-based line number, `\` continuations joined. */
function shLines(file: string): DocLine[] {
  const out: DocLine[] = [];
  let inSh = false;
  let pending: DocLine | null = null;
  readFileSync(path.join(REPO_DIR, file), 'utf8').split('\n').forEach((raw, i) => {
    if (raw.startsWith('```')) {
      inSh = !inSh && raw.trim() === '```sh';
      return;
    }
    if (!inSh) return;
    const text = raw.replace(/\s+#.*$/, '').trim();
    if (text === '' || text.startsWith('#')) return;
    const joined = pending === null ? text : `${pending.text} ${text}`;
    const start = pending === null ? i + 1 : pending.line;
    pending = joined.endsWith('\\') ? { file, line: start, text: joined.slice(0, -1).trim() } : null;
    if (pending === null) out.push({ file, line: start, text: joined });
  });
  return out;
}

